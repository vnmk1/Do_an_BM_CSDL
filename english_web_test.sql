-- 10. Enrollments (DK_COURSES)
CREATE TABLE DK_COURSES (
    dk_courses_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    course_id NUMBER NOT NULL,
    enroll_date DATE DEFAULT SYSDATE,
    status VARCHAR2(20) DEFAULT 'active',
    FOREIGN KEY (student_id) REFERENCES Users(user_id),
    FOREIGN KEY (course_id) REFERENCES Courses(course_id),
    UNIQUE (student_id, course_id)
);

-- 11. Feedback (tạo trước để Grades dùng)
CREATE TABLE Feedback (
    feedback_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id NUMBER NOT NULL,
    student_id NUMBER NOT NULL,
    exercise_id NUMBER,
    content CLOB NOT NULL,
    created_at DATE DEFAULT SYSDATE,
    FOREIGN KEY (teacher_id) REFERENCES Users(user_id),
    FOREIGN KEY (student_id) REFERENCES Users(user_id),
    FOREIGN KEY (exercise_id) REFERENCES Exercises(exercise_id)
);

-- 12. Grades
CREATE TABLE Grades (
    dk_courses_id NUMBER NOT NULL,
    exercise_id NUMBER NOT NULL,
    score NUMBER(5,2) CHECK (score BETWEEN 0 AND 100),
    date_graded DATE DEFAULT SYSDATE,
    feedback_id NUMBER,
    PRIMARY KEY (dk_courses_id, exercise_id),
    FOREIGN KEY (dk_courses_id) REFERENCES DK_COURSES(dk_courses_id) ON DELETE CASCADE,
    FOREIGN KEY (exercise_id) REFERENCES Exercises(exercise_id),
    FOREIGN KEY (feedback_id) REFERENCES Feedback(feedback_id)
);

-- 13. Payments
CREATE TABLE Payments (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL,
    course_id NUMBER NOT NULL,
    amount NUMBER(10,2) NOT NULL,
    payment_date DATE DEFAULT SYSDATE,
    status VARCHAR2(20) DEFAULT 'pending',
    FOREIGN KEY (student_id) REFERENCES Users(user_id),
    FOREIGN KEY (course_id) REFERENCES Courses(course_id)
);

-- 14. Notifications
CREATE TABLE Notifications (
    notification_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    message CLOB NOT NULL,
    type VARCHAR2(50),
    sent_date DATE DEFAULT SYSDATE,
    FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE
);
-- 15. Progress
CREATE TABLE Progress (
    dk_courses_id NUMBER NOT NULL,
    lesson_id NUMBER NOT NULL,
    progress NUMBER(5,2) CHECK (progress BETWEEN 0 AND 100),
    last_updated DATE DEFAULT SYSDATE,
    PRIMARY KEY (dk_courses_id, lesson_id),
    FOREIGN KEY (dk_courses_id) REFERENCES DK_COURSES(dk_courses_id) ON DELETE CASCADE,
    FOREIGN KEY (lesson_id) REFERENCES Lessons(lesson_id)
);


