-- 2. Users
CREATE TABLE Users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name NVARCHAR2(50) UNIQUE NOT NULL,
    password_hash VARCHAR2(256) NULL, 
    email VARCHAR2(100) NOT NULL UNIQUE,
    full_name VARCHAR2(100),
    create_at DATE DEFAULT SYSDATE
);

/* THÊM LẠI HÀM HASH_PASSWORD */
CREATE OR REPLACE FUNCTION hash_password(p_password VARCHAR2)
RETURN VARCHAR2
IS
    v_hash RAW(32);
BEGIN
    v_hash := DBMS_CRYPTO.HASH(UTL_RAW.CAST_TO_RAW(p_password), DBMS_CRYPTO.HASH_SH256);
    RETURN RAWTOHEX(v_hash); -- trả về dạng HEX
END;
