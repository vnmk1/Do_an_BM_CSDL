-- 4. Languages
CREATE TABLE Languages (
    language_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(50) NOT NULL UNIQUE
);

-- 5. Courses
CREATE TABLE Courses (
    course_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title NVARCHAR2(200) NOT NULL,
    description CLOB,
    teacher_id NUMBER NOT NULL,
    language_id NUMBER NOT NULL,
    fee NUMBER(10,2) DEFAULT 0,
    create_at DATE DEFAULT SYSDATE,
    CONSTRAINT FK_TEACHER FOREIGN KEY (teacher_id) REFERENCES Users(user_id),
    CONSTRAINT FK_LANG FOREIGN KEY (language_id) REFERENCES Languages(language_id)
);

-- 6. Modules
CREATE TABLE Modules (
    module_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id NUMBER NOT NULL,
    title NVARCHAR2(200) NOT NULL,
    order_num NUMBER,
    CONSTRAINT FK_MODULE_COURSE FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE
);


-- 7. Lessons
CREATE TABLE Lessons (
    lesson_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id NUMBER NOT NULL,
    course_id NUMBER NOT NULL,
    order_num NUMBER,
    title NVARCHAR2(200) NOT NULL,
    content_type NVARCHAR2(50),
    CONSTRAINT FK_LESSON_MODULE FOREIGN KEY (module_id) REFERENCES Modules(module_id) ON DELETE CASCADE,
    CONSTRAINT FK_LESSON_COURSE FOREIGN KEY (course_id) REFERENCES Courses(course_id) ON DELETE CASCADE
);

-- 8. Contents
CREATE TABLE Contents (
    content_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title NVARCHAR2(200),
    type VARCHAR2(50) NOT NULL,
    file_path NVARCHAR2(500),
    lesson_id NUMBER NOT NULL,
    course_id NUMBER NOT NULL,
    FOREIGN KEY (lesson_id) REFERENCES Lessons(lesson_id) ON DELETE CASCADE
);

-- 9. Exercises
CREATE TABLE Exercises (
    exercise_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title NVARCHAR2(200) NOT NULL,
    type VARCHAR2(50) NOT NULL,
    content CLOB,
    lesson_id NUMBER NOT NULL,
    FOREIGN KEY (lesson_id) REFERENCES Lessons(lesson_id) ON DELETE CASCADE
);

