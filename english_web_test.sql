-- Trigger: Đảm bảo chỉ teacher được tạo course
CREATE OR REPLACE TRIGGER trg_check_quyen_role
BEFORE INSERT OR UPDATE ON Courses
FOR EACH ROW
DECLARE 
    v_role_count NUMBER;
BEGIN 
    SELECT COUNT(*)
    INTO v_role_count
    FROM User_roles ur
    JOIN Roles r ON ur.role_id = r.role_id
    WHERE ur.user_id = :NEW.teacher_id 
      AND r.role_name = 'teacher';
    
    IF v_role_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Chi co "teacher" moi duoc tao khoa hoc');
    END IF;
END;
/

